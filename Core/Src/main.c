/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */
	__disable_irq();
	SCB->VTOR = 0x08040000;
	__enable_irq();
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_SPI1_Init();
  /* USER CODE BEGIN 2 */

  GPIO_Init();
  TIM1_Init_and_Start();
  EXTI_Init();
  usart1_init_and_start();
  usart2_init_and_start();
  usart3_init_and_start();
  usart4_init_and_start();


  GPIOB->ODR |= 1 << 9;  								//nWP   initial state
  GPIOB->ODR |= 1 << 10; 								//nCS   initial state

  global_mode_setting(); 								//endless cycle until user choose mode


  index_show_set();
  structures_init();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {

	  // For Ornament Mode
	  for(int i = 0; i < SEQAMOUNT; i++)
	  {
		  if(seq_irq_cnt[i] > 0)
		  {
			  seq_irq_cnt[i]--;
			  real_pop_from_sequencer(&sequencer_arr[i], i);
		  }
	  }

	  empty_trig_queue(); // Эта очередь заполняется и секвенсором и сплиттером, когда отправляешь края диапазона

	  message_assambling();
	  if(incoming_note.complete_flag == 1)
	  {
		  incoming_note_processing(1);
	  }
	  if(incoming_CC_msg.complete_flag == 1)
	  {
		  incoming_CC_processing(1);
	  }

	  // Second midi in

	  message_assambling2();
	  if(incoming_note2.complete_flag == 1)
	  {
		  incoming_note_processing(2);
	  }
	  if(incoming_CC_msg2.complete_flag == 1)
	  {
		  incoming_CC_processing(2);
	  }

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

